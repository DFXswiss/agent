def valid_detail(action: str) -> dict[str, Any]:
    """The detail of the contract fixture `fixtures/audit/<action>/valid/basic.json` (a detail that fits)."""
    return _load(CONTRACTS / "fixtures" / "audit" / action / "valid" / "basic.json")


def render() -> str:
    """The source text of the module (before `ruff format`)."""
    return HEADER + repr(resolved()) + "\n"


if __name__ == "__main__":
    MODULE.write_text(render(), encoding="utf-8")
